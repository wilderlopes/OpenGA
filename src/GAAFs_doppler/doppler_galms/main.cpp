// Function to load signal from file
std::vector<mvType> load_signal_from_file(const std::string& filename, int N) {
    std::vector<mvType> signal(N);
    std::ifstream file(filename);
    
    if (!file.is_open()) {
        std::cout << "Warning: Could not open " << filename << ". Using generated data instead." << std::endl;
        // Generate default signal if file not found
        std::default_random_engine gen;
        std::normal_distribution<double> dist(0, 1);
        for (int i = 0; i < N; i++) {
            signal[i] = mvType{dist(gen), dist(gen)};
        }
        return signal;
    }
    
    for (int i = 0; i < N && !file.eof(); i++) {
        double real_part, imag_part;
        if (file >> real_part >> imag_part) {
            signal[i] = mvType{real_part, imag_part};
        } else {
            signal[i] = mvType{0, 0};
        }
    }
    
    file.close();
    return signal;
}

int main(int argc, char* argv[])
{

    double error_galms, emse_galms, msd_galms;
    double MSE_theory = 0, EMSE_theory = 0;
    double mu_galms = 5e-3;
    double realizations = 10;
    double iterations = 1000;
    double var_v = 0;
    int M = 4; //number of taps

    std::stringstream str_M(argv[1]);
    str_M >> M;

    std::stringstream str_realizations(argv[2]);
    str_realizations >> realizations;

    std::stringstream str_iterations(argv[3]);
    str_iterations >> iterations;

    std::stringstream str_mu_galms(argv[4]);
    str_mu_galms >> mu_galms;

    std::stringstream str_var_v(argv[5]);
    str_var_v >> var_v;

    // Initialize rotor variables for the new filter
    mvType r_old{1, 0};  // Initialize as identity rotor (1 + 0*e12)
    mvType r_new{1, 0};
    mvType x_old{0, 0};  // Previous signal input
    mvType x_current{0, 0}; // Current signal input
    mvType v{0, 0}; // noise

    std::default_random_engine u;
    std::normal_distribution<double> normaldist(0,1); //Gaussian Distribution, mean=0, stddev=1;

    // Load input signal from file generated by Python
    std::vector<mvType> input_signal = load_signal_from_file("input_signal.txt", iterations);
    
    // Storage for estimated signals
    std::vector<mvType> x_estimated_avg(iterations, mvType{0, 0});

    std::vector<double> MSE_new_filter_avg;  // For the new filter

    // Resizing the following vectors to allocate memory
    MSE_new_filter_avg.resize(iterations);

for (size_t j = 0; j < realizations; ++j)
{

    std::cout << "Realization = " << j+1 << " of " << realizations << std::endl;

    // Reset rotor for each realization
    r_old = mvType{1, 0};  // Identity rotor
    x_old = mvType{0, 0};

    for (int n=0; n < M; n++) //populating the arrays for compatibility
    {
        // Keep minimal initialization for any remaining dependencies
    }

    // Storage for this realization's estimated signals
    std::vector<mvType> x_estimated_realization(iterations, mvType{0, 0});

    // Redefining MSE vectors before each realization
    std::vector<double> MSE_new_filter;

for (size_t i = 0; i < iterations; ++i)
    {
        // Use the loaded signal instead of generating new ones
        x_current = input_signal[i];
        std::cout << "x_current = " << x_current << std::endl;

        // Generate noise for this realization
        for (size_t k = 0; k < 2; ++k)
        {
            v[k] = normaldist(u) * sqrt(var_v); // Scale noise properly
        }
        
        // Add noise to current signal
        mvType x_noisy = mvType{x_current[0] + v[0], x_current[1] + v[1]};

        // NEW ROTOR-BASED ADAPTIVE FILTER IMPLEMENTATION
        // r_i = r_{i-1} + μ * reverse(x_i) * (r_{i-1} * reverse(x_{i-1}) * reverse(r_{i-1})) * r_{i-1}
        
        mvType x_estimate = mvType{0, 0};
        
        if (i > 0) // Skip first iteration since we need x_{i-1}
        {
            // Calculate reverse operations
            mvType rev_x_current = ~x_current;        // reverse(x_i)
            mvType rev_x_old = ~x_old;                 // reverse(x_{i-1})
            mvType rev_r_old = ~r_old;                 // reverse(r_{i-1})
            
            // Calculate the middle term: (r_{i-1} * reverse(x_{i-1}) * reverse(r_{i-1}))
            mvType middle_term = eval(r_old * rev_x_old * rev_r_old);
            
            // Calculate the update term: μ * reverse(x_i) * middle_term * r_{i-1}
            mvType update_term = eval(mu_galms * rev_x_current * middle_term * r_old);
            
            // Update the rotor: r_i = r_{i-1} + update_term
            r_new = eval(r_old + update_term);
            
            // Normalize the rotor to maintain unit magnitude (important for rotors)
            double rotor_magnitude = eval(magnitude(r_new));
            if (rotor_magnitude > 1e-10) // Avoid division by zero
            {
                double inv_magnitude = 1.0 / rotor_magnitude;
                r_new = eval(inv_magnitude * r_new);
            }
            
            // Calculate estimation: x_i_estimate = r_i * x_{i-1} * reverse(r_i)
            x_estimate = eval(r_new * x_old * (~r_new));
            
            // Calculate error for the new filter
            mvType estimation_error = eval(x_current - x_estimate);
            double new_filter_error = eval(magnitude(estimation_error));
            MSE_new_filter.push_back(pow(new_filter_error, 2));
        }
        else
        {
            // For first iteration, just store zero error and use current signal as estimate
            MSE_new_filter.push_back(0.0);
            x_estimate = x_current;
        }
        
        // Store estimated signal for this realization
        x_estimated_realization[i] = x_estimate;
        
        // Update for next iteration
        r_old = r_new;
        x_old = x_current;
    }

    // Average the results over realizations
    for (size_t r = 0; r < iterations; ++r)
    {
        MSE_new_filter_avg[r] = MSE_new_filter_avg[r] + MSE_new_filter[r]/realizations;
        
        // Average the estimated signals
        double inv_realizations = 1.0 / realizations;
        x_estimated_avg[r] = eval(x_estimated_avg[r] + eval(inv_realizations * x_estimated_realization[r]));
    }
}

    // Calculate theoretical values (simplified for rotor filter)
    //double MSE_theory = var_v + mu_galms * var_v / (1 - mu_galms);
    
    std::cout << "Iterations = " << iterations << std::endl;
    std::cout << "Realizations = " << realizations << std::endl;
    std::cout << "Step size = " << mu_galms << std::endl;
    std::cout << "Final rotor estimate = " << r_new << std::endl;

    // SAVING ROTOR FILTER RESULTS
    std::ofstream output_MSE_new_filter("./MSE_new_filter.out");
    std::ostream_iterator<double> output_iterator_MSE_new_filter(output_MSE_new_filter, "\n");
    std::copy(MSE_new_filter_avg.begin(), MSE_new_filter_avg.end(), output_iterator_MSE_new_filter);

    std::ofstream output_MSE_theory("./MSE_theory.out");
    output_MSE_theory << MSE_theory << '\n';

    // Save estimated signal
    std::ofstream output_x_estimated("./x_estimated.out");
    for (size_t i = 0; i < iterations; ++i)
    {
        output_x_estimated << x_estimated_avg[i][0] << " " << x_estimated_avg[i][1] << '\n';
    }

    // Save input signal for reference
    std::ofstream output_x_input("./x_input.out");
    for (size_t i = 0; i < iterations; ++i)
    {
        output_x_input << input_signal[i][0] << " " << input_signal[i][1] << '\n';
    }

    // Save final rotor
    std::ofstream output_rotor("./final_rotor.out");
    output_rotor << r_new << '\n';

    return 0;
}
